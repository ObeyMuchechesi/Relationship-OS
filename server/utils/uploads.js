import multer from 'multer';
import path from 'path';
import os from 'os';
import fs from 'fs';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Local dev keeps files in server/uploads (served statically).
// On Vercel the filesystem is read-only, so without object storage
// uploads land in /tmp (ephemeral per warm instance).
export const uploadsDir = process.env.VERCEL
  ? path.join(os.tmpdir(), 'uploads')
  : path.join(__dirname, '..', 'uploads');

fs.mkdirSync(uploadsDir, { recursive: true });

// Cloudflare R2 (S3-compatible) — used when all four variables are present.
// Without them the app falls back to local disk storage, so deploying
// before the keys exist is safe.
const r2Config = (() => {
  const accountId = process.env.CLOUDFLARE_ACCOUNT_ID;
  const accessKeyId = process.env.CLOUDFLARE_R2_ACCESS_KEY_ID;
  const secretAccessKey = process.env.CLOUDFLARE_R2_SECRET_ACCESS_KEY;
  const bucket = process.env.R2_BUCKET_NAME;
  if (accountId && accessKeyId && secretAccessKey && bucket) {
    return { accountId, accessKeyId, secretAccessKey, bucket };
  }
  return null;
})();

export const useR2 = Boolean(r2Config);

// Optional override for local testing against an S3-compatible mock.
const endpoint =
  process.env.R2_ENDPOINT || (r2Config && `https://${r2Config.accountId}.r2.cloudflarestorage.com`);

let clientPromise = null;
async function r2Client() {
  if (!clientPromise) {
    clientPromise = import('@aws-sdk/client-s3').then(
      ({ S3Client }) =>
        new S3Client({
          region: 'auto',
          endpoint,
          forcePathStyle: true,
          credentials: {
            accessKeyId: r2Config.accessKeyId,
            secretAccessKey: r2Config.secretAccessKey,
          },
        })
    );
  }
  return clientPromise;
}

const safeName = (name) => (name || 'file').replace(/[^a-zA-Z0-9._-]/g, '_');
const objectKey = (name) => `${Date.now()}-${Math.round(Math.random() * 1e9)}-${safeName(name)}`;

// Store an uploaded multer file in R2; returns the public path to serve it by.
export async function putUpload(file) {
  const { PutObjectCommand } = await import('@aws-sdk/client-s3');
  const s3 = await r2Client();
  const key = objectKey(file.originalname);
  await s3.send(
    new PutObjectCommand({
      Bucket: r2Config.bucket,
      Key: key,
      Body: file.buffer,
      ContentType: file.mimetype,
    })
  );
  return `/uploads/${key}`;
}

// Fetch an object back for the /uploads/:key proxy route.
export async function getUpload(key) {
  const { GetObjectCommand } = await import('@aws-sdk/client-s3');
  const s3 = await r2Client();
  return s3.send(new GetObjectCommand({ Bucket: r2Config.bucket, Key: key }));
}

// With R2, files are buffered in memory (no writable disk on Vercel);
// the request-body cap still applies. Without R2, disk storage as before.
const maxSize = useR2 || process.env.VERCEL ? 4 * 1024 * 1024 : 25 * 1024 * 1024;

const storage = useR2
  ? multer.memoryStorage()
  : multer.diskStorage({
      destination: (req, file, cb) => cb(null, uploadsDir),
      filename: (req, file, cb) => {
        cb(null, `${Date.now()}-${Math.round(Math.random() * 1e9)}-${safeName(file.originalname)}`);
      },
    });

export const upload = multer({ storage, limits: { fileSize: maxSize } });

// Keys are generated by us as `timestamp-random-name`, so reject anything else.
export const validUploadKey = (key) => /^[a-zA-Z0-9._-]{1,200}$/.test(key);
