import multer from 'multer';
import path from 'path';
import os from 'os';
import fs from 'fs';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Local dev keeps files in server/uploads (served statically).
// On Vercel the filesystem is read-only, so without object storage
// uploads land in /tmp (ephemeral per warm instance).
export const uploadsDir = process.env.VERCEL
  ? path.join(os.tmpdir(), 'uploads')
  : path.join(__dirname, '..', 'uploads');

fs.mkdirSync(uploadsDir, { recursive: true });

// S3-compatible object storage (Backblaze B2 by default; any S3-compatible
// endpoint works). Used when all five variables are present; without them the
// app falls back to local disk storage, so deploying before keys exist is safe.
const storageConfig = (() => {
  const endpoint = process.env.S3_ENDPOINT;
  const region = process.env.S3_REGION;
  const accessKeyId = process.env.S3_ACCESS_KEY_ID;
  const secretAccessKey = process.env.S3_SECRET_ACCESS_KEY;
  const bucket = process.env.S3_BUCKET;
  if (endpoint && region && accessKeyId && secretAccessKey && bucket) {
    return { endpoint, region, accessKeyId, secretAccessKey, bucket };
  }
  return null;
})();

export const useStorage = Boolean(storageConfig);

let clientPromise = null;
async function storageClient() {
  if (!clientPromise) {
    clientPromise = import('@aws-sdk/client-s3').then(
      ({ S3Client }) =>
        new S3Client({
          endpoint: storageConfig.endpoint,
          region: storageConfig.region,
          // Path-style addressing (…/bucket/key) is what Backblaze documents;
          // set S3_FORCE_PATH_STYLE=false for endpoints that need virtual-host.
          forcePathStyle: process.env.S3_FORCE_PATH_STYLE !== 'false',
          credentials: {
            accessKeyId: storageConfig.accessKeyId,
            secretAccessKey: storageConfig.secretAccessKey,
          },
        })
    );
  }
  return clientPromise;
}

const safeName = (name) => (name || 'file').replace(/[^a-zA-Z0-9._-]/g, '_');
const objectKey = (name) => `${Date.now()}-${Math.round(Math.random() * 1e9)}-${safeName(name)}`;

// Store an uploaded file in the bucket; returns the public path to serve it by.
export async function putUpload(file) {
  const { PutObjectCommand } = await import('@aws-sdk/client-s3');
  const s3 = await storageClient();
  const key = objectKey(file.originalname);
  await s3.send(
    new PutObjectCommand({
      Bucket: storageConfig.bucket,
      Key: key,
      Body: file.buffer,
      ContentType: file.mimetype,
    })
  );
  return `/uploads/${key}`;
}

// Fetch an object back for the /uploads/:key proxy route.
export async function getUpload(key) {
  const { GetObjectCommand } = await import('@aws-sdk/client-s3');
  const s3 = await storageClient();
  return s3.send(new GetObjectCommand({ Bucket: storageConfig.bucket, Key: key }));
}

// With object storage, files are buffered in memory (no writable disk on
// Vercel); the request-body cap still applies. Without it, disk as before.
const maxSize = useStorage || process.env.VERCEL ? 4 * 1024 * 1024 : 25 * 1024 * 1024;

const storage = useStorage
  ? multer.memoryStorage()
  : multer.diskStorage({
      destination: (req, file, cb) => cb(null, uploadsDir),
      filename: (req, file, cb) => {
        cb(null, `${Date.now()}-${Math.round(Math.random() * 1e9)}-${safeName(file.originalname)}`);
      },
    });

export const upload = multer({ storage, limits: { fileSize: maxSize } });

// Keys are generated by us as `timestamp-random-name`, so reject anything else.
export const validUploadKey = (key) => /^[a-zA-Z0-9._-]{1,200}$/.test(key);

// Where a just-uploaded multer file lives: object storage when configured, disk otherwise.
export const storedPath = (file) =>
  useStorage ? putUpload(file) : Promise.resolve(`/uploads/${file.filename}`);
